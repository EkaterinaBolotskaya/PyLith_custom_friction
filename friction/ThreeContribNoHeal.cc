contrib::friction::ThreeContribNoHeal::_nondimProperties(PylithScalar* const values,
						      const int nvalues) const
{ // _nondimProperties
  // Check consistency of arguments.
  assert(_normalizer);
  assert(values);
  assert(nvalues == _ThreeContribNoHeal::numProperties);

  // Get scales needed to nondimensional parameters from the
  // Nondimensional object.
  const PylithScalar lengthScale = _normalizer->lengthScale();
  const PylithScalar timeScale = _normalizer->timeScale();
  const PylithScalar pressureScale = _normalizer->pressureScale();
  const PylithScalar velocityScale = lengthScale / timeScale;
  const PylithScalar inverselengthScale = 1.0 / lengthScale;

  // Use the Nondimensional::nondimensionalize() function to
  // nondimensionalize the quantities using the appropriate scale.
  values[p_u_dp] = _normalizer->nondimensionalize(values[p_u_dp], lengthScale);
  values[p_u_dhalf] = _normalizer->nondimensionalize(values[p_u_dhalf], lengthScale);
  values[p_k] = _normalizer->nondimensionalize(values[p_k], inverselengthScale);
  values[p_delta_u_fpp] = _normalizer->nondimensionalize(values[p_delta_u_fpp], lengthScale);
  values[p_delta_u_f] = _normalizer->nondimensionalize(values[p_delta_u_f], lengthScale);
  values[p_u_dam] = _normalizer->nondimensionalize(values[p_u_dam], lengthScale);

} // _nondimProperties

