// ----------------------------------------------------------------------
// Compute friction from properties and state variables.
PylithScalar
contrib::friction::ThreeContribNoHeal::_calcFriction(const PylithScalar t,
						  const PylithScalar slip,
						  const PylithScalar slipRate,
						  const PylithScalar normalTraction,
						  const PylithScalar* properties,
						  const int numProperties,
						  const PylithScalar* stateVars,
						  const int numStateVars)
{ // _calcFriction
  // Check consistency of arguments.
  assert(properties);
  assert(_ThreeContribNoHeal::numProperties == numProperties);
  assert(numStateVars);
  assert(_ThreeContribNoHeal::numStateVars == numStateVars);

  // Compute friction traction.
  PylithScalar friction = 0.0;
  PylithScalar mu_f = 0.0;
  PylithScalar mu_dam = 0.0;
  PylithScalar mu_fric = 0.0;
  PylithScalar mu_dil = 0.0;
  PylithScalar u_fp = 0.0;
  PylithScalar u_fpp = 0.0;
  PylithScalar delta_u_dam = 0.0;
  if (normalTraction <= 0.0) {
    // if fault is in compression
    const PylithScalar slipPrev = stateVars[s_slipPrev];
    const PylithScalar slipCum = stateVars[s_slipCum] + fabs(slip - slipPrev);

    u_fp = properties[p_mu_fp] / properties[p_k];
    u_fpp = u_fp + properties[p_delta_u_fpp];
    delta_u_dam = properties[p_delta_u_f];

    mu_dil = tan ( properties[p_psi_p] * 3.14159265358979323846 / 180.0 ) *
	  exp(- log (2.0) * pow((slipCum - properties[p_u_dp]) / (properties[p_u_dhalf] - properties[p_u_dp]), 2.0));

    if (properties[p_mu_fp] <= properties[p_mu_ss]) {
        u_fpp = u_fp;
    }

    if (slipCum < u_fp) {
	// if/else linear slip-weakening form of mu_f 
	mu_fric = properties[p_k] * slipCum ;
	  } else if (slipCum < u_fpp) {
	mu_fric = properties[p_mu_fp] +
	  (properties[p_mu_fpp] - properties[p_mu_fp]) * (slipCum - u_fp) / properties[p_delta_u_fpp];
      } else {
	mu_fric = properties[p_mu_ss] + (properties[p_mu_fpp] - properties[p_mu_ss]) *
	  exp(-(slipCum - u_fpp) / properties[p_delta_u_f]);
      } // if/else

    if (slipCum < properties[p_u_dam]) {
	// if/else linear slip-weakening form of mu_f 
	mu_dam = 0.0;
	  } else {
	mu_dam = properties[p_mu_dp] *
	  exp(-(slipCum - properties[p_u_dam]) / delta_u_dam);
      } // if/else

    mu_f = mu_dil + mu_fric + mu_dam;
	
	
	mu_f = std::max(mu_f, properties[p_mu_ss]);
	
    friction = -mu_f * normalTraction;
  } else { // else
    friction = 0.0;
  } // if/else

  PetscLogFlops(10);

  return friction;
} // _calcFriction

// ----------------------------------------------------------------------
// Compute derivative of friction with slip from properties and state variables.
PylithScalar
contrib::friction::ThreeContribNoHeal::_calcFrictionDeriv(const PylithScalar t,
						       const PylithScalar slip,
						       const PylithScalar slipRate,
						       const PylithScalar normalTraction,
						       const PylithScalar* properties,
						       const int numProperties,
						       const PylithScalar* stateVars,
						       const int numStateVars)
{ // _calcFrictionDeriv
  // Check consistency of arguments.
  assert(properties);
  assert(_ThreeContribNoHeal::numProperties == numProperties);
  assert(numStateVars);
  assert(_ThreeContribNoHeal::numStateVars == numStateVars);
  
  // Compute friction traction.
  PylithScalar friction = 0.0;
  PylithScalar mu_f = 0.0;
  PylithScalar mu_dam = 0.0;
  PylithScalar mu_fric = 0.0;
  PylithScalar mu_dil = 0.0;
  PylithScalar u_fp = 0.0;
  PylithScalar u_fpp = 0.0;
  PylithScalar delta_u_dam = 0.0;
  if (normalTraction <= 0.0) {
    // if fault is in compression
    const PylithScalar slipPrev = stateVars[s_slipPrev];
    const PylithScalar slipCum = stateVars[s_slipCum] + fabs(slip - slipPrev);

    u_fp = properties[p_mu_fp] / properties[p_k];
    u_fpp = u_fp + properties[p_delta_u_fpp];
    delta_u_dam = properties[p_delta_u_f];

    mu_dil = tan ( properties[p_psi_p] * 3.14159265358979323846 / 180.0 ) *
	  exp(- log (2.0) * pow((slipCum - properties[p_u_dp]) / (properties[p_u_dhalf] - properties[p_u_dp]), 2.0));

    if (properties[p_mu_fp] <= properties[p_mu_ss]) {
        u_fpp = u_fp;
    }

    if (slipCum < u_fp) {
	// if/else linear slip-weakening form of mu_f 
	mu_fric = properties[p_k] * slipCum ;
	  } else if (slipCum < u_fpp) {
	mu_fric = properties[p_mu_fp] +
	  (properties[p_mu_fpp] - properties[p_mu_fp]) * (slipCum - u_fp) / properties[p_delta_u_fpp];
      } else {
	mu_fric = properties[p_mu_ss] + (properties[p_mu_fpp] - properties[p_mu_ss]) *
	  exp(-(slipCum - u_fpp) / properties[p_delta_u_f]);
      } // if/else

    if (slipCum < properties[p_u_dam]) {
	// if/else linear slip-weakening form of mu_f 
	mu_dam = 0.0;
	  } else {
	mu_dam = properties[p_mu_dp] *
	  exp(-(slipCum - properties[p_u_dam]) / delta_u_dam);
      } // if/else

    mu_f = mu_dil + mu_fric + mu_dam;
	
	
	mu_f = std::max(mu_f, properties[p_mu_ss]);
	
    friction = -mu_f * normalTraction;
  } else { // else
    friction = 0.0;
  } // if/else

  // Compute friction traction.
  PylithScalar frictionDeriv = 0.0;
  PylithScalar mu_damDeriv = 0.0;
  PylithScalar mu_fricDeriv = 0.0;
  PylithScalar mu_dilDeriv = 0.0;
  
  if (normalTraction <= 0.0) {
    // if fault is in compression
	const PylithScalar slipPrev = stateVars[s_slipPrev];
    const PylithScalar slipCum = stateVars[s_slipCum] + fabs(slip - slipPrev);

    u_fp = properties[p_mu_fp] / properties[p_k];
    u_fpp = u_fp + properties[p_delta_u_fpp];
    delta_u_dam = properties[p_delta_u_f];

    mu_dilDeriv = log (2.0) * tan ( properties[p_psi_p] * 3.14159265358979323846 / 180.0 ) *
	  exp(-log (2.0) * pow((properties[p_u_dp] - slipCum)/(properties[p_u_dp] - properties[p_u_dhalf]),2)) *
	  (2.0 * properties[p_u_dp] - 2.0 * slipCum) / pow((properties[p_u_dp] - properties[p_u_dhalf]),2);

    if (properties[p_mu_fp] <= properties[p_mu_ss]) {
        u_fpp = u_fp;
    }

    if (slipCum < u_fp) {
      mu_fricDeriv = properties[p_k];
    } else if (slipCum < u_fpp) {
		mu_fricDeriv = (properties[p_mu_fpp] - properties[p_mu_fp]) / properties[p_delta_u_fpp];
      } else {
		mu_fricDeriv = (properties[p_mu_ss] - properties[p_mu_fpp]) *
		exp(-(slipCum - u_fpp) / properties[p_delta_u_f]) / properties[p_delta_u_f];
    }

    if (slipCum < properties[p_u_dam]) {
	// if/else linear slip-weakening form of mu_f 
	mu_damDeriv = 0.0;
	  } else {
	mu_damDeriv = - properties[p_mu_dp] *
	  exp(-(slipCum - properties[p_u_dam]) / delta_u_dam) / delta_u_dam;
      } // if/else
  
    frictionDeriv = - normalTraction * (mu_dilDeriv + mu_fricDeriv + mu_damDeriv);
	
	if (mu_f <= properties[p_mu_ss]) {
	frictionDeriv = 0; 	}
	
	} else { // else
    frictionDeriv = 0.0;
  }
		
   // if/else
  return frictionDeriv;
} // _calcFrictionDeriv

