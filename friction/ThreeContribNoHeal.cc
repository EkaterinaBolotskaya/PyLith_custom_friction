// Update state variables (for next time step).
void
contrib::friction::ThreeContribNoHeal::_updateStateVars(const PylithScalar t,
						     const PylithScalar slip,
						     const PylithScalar slipRate,
						     const PylithScalar normalTraction,
						     PylithScalar* const stateVars,
						     const int numStateVars,
						     const PylithScalar* properties,
						     const int numProperties)
{ // _updateStateVars
  // Check consistency of arguments.
  assert(properties);
  assert(_ThreeContribNoHeal::numProperties == numProperties);
  assert(numStateVars);
  assert(_ThreeContribNoHeal::numStateVars == numStateVars);
  
  const PylithScalar tolerance = 0;
  if (slipRate >= tolerance) {
    const PylithScalar slipPrev = stateVars[s_slipPrev];

    stateVars[s_slipPrev] = slip;
    stateVars[s_slipCum] += fabs(slip - slipPrev);
  } else {
    // Sliding has stopped, so reset state variables.
    stateVars[s_slipPrev] = slip;
    stateVars[s_slipCum] = 0.0;
  } // else
	  
  //const PylithScalar slipPrev = stateVars[s_slipPrev];
  //stateVars[s_slipPrev] = slip;
  //stateVars[s_slipCum] += fabs(slip - slipPrev);
  
} // _updateStateVars


