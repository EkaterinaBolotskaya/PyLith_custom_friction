// ----------------------------------------------------------------------
// Compute properties from values in spatial database.
void
contrib::friction::ThreeContribNoHeal::_dbToProperties(PylithScalar* const propValues,
						    const pylith::scalar_array& dbValues) const
{ // _dbToProperties
  // Check consistency of arguments
  assert(propValues);
  const int numDBValues = dbValues.size();
  assert(_ThreeContribNoHeal::numDBProperties == numDBValues);

  // Extract values from array using our defined indices.
  const PylithScalar psi_p = dbValues[db_psi_p];
  const PylithScalar u_dp = dbValues[db_u_dp];
  const PylithScalar u_dhalf = dbValues[db_u_dhalf];
  const PylithScalar k = dbValues[db_k];
  const PylithScalar mu_fpp = dbValues[db_mu_fpp];
  const PylithScalar mu_fp = dbValues[db_mu_fp];
  const PylithScalar delta_u_fpp = dbValues[db_delta_u_fpp];
  const PylithScalar mu_ss = dbValues[db_mu_ss];
  const PylithScalar delta_u_f = dbValues[db_delta_u_f];
  const PylithScalar u_dam = dbValues[db_u_dam];
  const PylithScalar mu_dp = dbValues[db_mu_dp];

  // Check for reasonable values. If user supplied unreasonable values
  // throw an exception.
  if (psi_p < 0.0) {
    std::ostringstream msg;
    msg << "Spatial database returned negative value for peak "
	<< "dilation angle.\n"
	<< "Peak dilation angle (psi_p): " << psi_p << "\n";
    throw std::runtime_error(msg.str());
  } // if
  
  if (u_dp < 0.0) {
    std::ostringstream msg;
    msg << "Spatial database returned negative value for slip at "
	<< "peak dilation.\n"
	<< "Slip at peak dilation (u_dp): " << u_dp << "\n";
    throw std::runtime_error(msg.str());
  } // if
  
  if (u_dhalf < 0.0) {
    std::ostringstream msg;
    msg << "Spatial database returned negative value for slip at "
	<< "half dilation.\n"
	<< "Slip at half dilation (u_dhalf): " << u_dhalf << "\n";
    throw std::runtime_error(msg.str());
  } // if
  
    if (k < 0.0) {
    std::ostringstream msg;
    msg << "Spatial database returned negative value for friction "
	<< "strengthening slope.\n"
	<< "Friction strengthening slope (k): " << k << "\n";
    throw std::runtime_error(msg.str());
  } // if
  
  if (mu_fpp < 0.0) {
    std::ostringstream msg;
    msg << "Spatial database returned negative value for friction "
	<< "coefficient after linear weakening.\n"
	<< "Friction coefficient after linear weakening (mu_fpp): " << mu_fpp << "\n";
    throw std::runtime_error(msg.str());
  } // if
  
  if (mu_fp < 0.0) {
    std::ostringstream msg;
    msg << "Spatial database returned negative value for peak "
	<< "friction coefficient.\n"
	<< "Peak friction coefficient (mu_fp): " << mu_fp << "\n";
    throw std::runtime_error(msg.str());
  } // if
  
  if (delta_u_fpp < 0.0) {
    std::ostringstream msg;
    msg << "Spatial database returned negative value for linear "
	<< "weakening distance.\n"
	<< "Linear weakening distance (delta_u_fpp): " << delta_u_fpp << "\n";
    throw std::runtime_error(msg.str());
  } // if

  if (mu_ss < 0.0) {
    std::ostringstream msg;
    msg << "Spatial database returned negative value for steady-state "
	<< "friction coefficient.\n"
	<< "Steady-state friction coefficient (mu_ss): " << mu_ss << "\n";
    throw std::runtime_error(msg.str());
  } // if

  // Compute parameters that we store from the user-supplied parameters.
  propValues[p_psi_p] = psi_p;
  propValues[p_u_dp] = u_dp;
  propValues[p_u_dhalf] = u_dhalf;
  propValues[p_k] = k;
  propValues[p_mu_fpp] = mu_fpp;
  propValues[p_mu_fp] = mu_fp;
  propValues[p_delta_u_fpp] = delta_u_fpp;
  propValues[p_mu_ss] = mu_ss;
  propValues[p_delta_u_f] = delta_u_f;
  propValues[p_u_dam] = u_dam;
  propValues[p_mu_dp] = mu_dp;

} // _dbToProperties

